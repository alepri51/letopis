/** Описание параметра: строка — у обязательного; у необязательного — ещё значение по умолчанию. */
export type ParamDoc = string | { text: string; default?: string; type?: string };

export interface ApiDoc {
  /** Что делает — если в JSDoc описания нет. */
  summary?: string;
  /** Подробности: дополняют JSDoc или summary. */
  details?: string;
  /** Параметры: имя (поле объекта — `opts.поле`, флаг CLI — `--флаг`) → описание. */
  params?: Record<string, ParamDoc>;
  /** Что возвращает. */
  returns?: string;
  /** Коды ошибок: код → когда. Пустой объект — собственных кодов нет. */
  errors?: Record<string, string>;
  /** Значение по умолчанию — у опций. */
  default?: string;
  /** Сигнатура — у инструментов MCP: в коде её нет. */
  signature?: string;
  /** Ещё пункты covers, чьи примеры показать (например, db.entity ← chain.entity). */
  examples?: string[];
}

