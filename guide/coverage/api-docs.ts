/**
 * Описания справочника API (guide/pages/reference), которых нет в JSDoc lib/src или которые JSDoc дополняют.
 * Ключ — id пункта, как в covers примеров: `chain.create`; `db.watch` — член корня квартиры `me` (тип `Room`; имена DB_METHODS);
 * `house.open` — консьерж `db` из `connect(pass)`; `keys.setPassword` — `me.keys`; `acl.check` — `me.acl`;
 * `setup.models`, `connect.cache` — опции; `mcptool.letopis_query`, `cli.load`. Страницы собирает scripts/gen-api.ts;
 * `--check` падает, если у пункта нет описания, параметра, значения по умолчанию, результата или списка ошибок.
 * Каждое утверждение сверено с кодом lib/src и lib/sql.
 */

/** Описание параметра: строка — у обязательного; у необязательного — ещё значение по умолчанию. */
export type ParamDoc = string | { text: string; default?: string; type?: string };

export interface ApiDoc {
  /** Что делает — если в JSDoc описания нет. */
  summary?: string;
  /** Подробности: дополняют JSDoc или summary. */
  details?: string;
  /** Параметры: имя (поле объекта — `opts.поле`, флаг CLI — `--флаг`) → описание. */
  params?: Record<string, ParamDoc>;
  /** Что возвращает. */
  returns?: string;
  /** Коды ошибок: код → когда. Пустой объект — собственных кодов нет. */
  errors?: Record<string, string>;
  /** Значение по умолчанию — у опций. */
  default?: string;
  /** Тип — у опции, когда тип в коде — параметр обобщения (P, E, T). */
  type?: string;
  /** Сигнатура — у инструментов MCP: в коде её нет. */
  signature?: string;
  /** Ещё пункты covers, чьи примеры показать (например, db.entity ← chain.entity). */
  examples?: string[];
}

